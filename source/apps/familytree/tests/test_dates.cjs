/* Run: node apps/familytree/tests/test_dates.cjs */
const assert=require('node:assert/strict');
const {age,compare}=require('../public/dates.js');
const exact=(value,unit='year')=>({value,unit,approximate:false});
const approximate=value=>({value,unit:'year',approximate:true});
const today=new Date(2026,9,27,12);
assert.deepEqual(age({birth_date:'2000-10-27'},today),exact(26));
assert.deepEqual(age({birth_date:'2000-10-28'},today),exact(25));
assert.deepEqual(age({birth_date:'2000-10-26'},today),exact(26));
assert.deepEqual(age({birth_year:2000},today),approximate(26));
assert.deepEqual(age({birth_date:'1900-03-02',deceased:true,death_date:'1980-07-08'},today),exact(80));
assert.deepEqual(age({birth_date:'1900-03-02',deceased:true,death_date:'1980-03-01'},today),exact(79));
assert.deepEqual(age({birth_year:1900,deceased:true,death_year:1980},today),approximate(80));
assert.equal(age({birth_date:'1941-04-12',deceased:true},today),null);
assert.equal(age({birth_year:1941,deceased:true},today),null);
assert.equal(age({deceased:true,death_date:'2020-01-01'},today),null);
assert.equal(age({},today),null);
assert.equal(age({birth_date:'2027-01-01'},today),null);
assert.equal(age({birth_date:'1980-03-02',deceased:true,death_date:'1979-03-02'}),null);
assert.deepEqual(age({birth_date:'2026-10-27'},today),exact(0,'day'));
assert.deepEqual(age({birth_date:'2026-10-20'},today),exact(7,'day'));
assert.deepEqual(age({birth_date:'2026-07-28'},today),exact(2,'month'));
assert.deepEqual(age({birth_date:'2026-07-27'},today),exact(3,'month'));
assert.deepEqual(age({birth_date:'2000-02-29'},new Date(2023,1,28,12)),exact(22));
assert.deepEqual(age({birth_date:'2000-02-29'},new Date(2023,2,1,12)),exact(23));
assert.deepEqual(age({birth_date:'2000-02-29'},new Date(2024,1,29,12)),exact(24));
assert.deepEqual(age({birth_date:'1900-02-29'},today),null);
assert.deepEqual(age({birth_date:'0090-01-01',deceased:true,death_date:'0100-01-01'}),exact(10));
assert.deepEqual(compare({birth_date:'1960-03-15'},{birth_date:'1985-03-15'}),{direction:'younger',...exact(25)});
assert.deepEqual(compare({birth_date:'1960-03-15'},{birth_date:'1985-03-14'}),{direction:'younger',...exact(24)});
assert.deepEqual(compare({birth_date:'1985-03-15'},{birth_date:'1960-03-15'}),{direction:'older',...exact(25)});
assert.deepEqual(compare({birth_year:1960},{birth_year:1985}),{direction:'younger',...approximate(25)});
assert.deepEqual(compare({birth_date:'1960-03-15'},{birth_year:1985}),{direction:'younger',...approximate(25)});
assert.deepEqual(compare({birth_year:1985},{birth_year:1985}),{direction:'sameYear',approximate:true});
assert.deepEqual(compare({birth_date:'1985-03-15'},{birth_date:'1985-03-15'}),{direction:'sameDate',approximate:false});
assert.deepEqual(compare({birth_date:'1985-03-15'},{birth_date:'1985-06-15'}),{direction:'younger',...exact(3,'month')});
assert.deepEqual(compare({birth_date:'1985-03-15'},{birth_date:'1985-03-18'}),{direction:'younger',...exact(3,'day')});
assert.equal(compare({birth_year:1985},{}),null);
// A deceased parent's lifespan must never be subtracted from a living child's age.
assert.deepEqual(compare({birth_year:1941,deceased:true,death_year:2022},{birth_year:1967}),{direction:'younger',...approximate(26)});
console.log('PASS: 33 age and birth-date comparison cases, including birthdays, leap days, infants, early years, missing dates, partial dates and deceased relatives.');
