  // A language file replaces window._i18n wholesale, so the app's own table is
  // merged in again on every load rather than only once at startup.
  var tables = { en: en, bg: bg, de: de, es: es, fr: fr, ja: ja, 'pt-BR': ptBR, ru: ru, 'zh-CN': zhCN };

  function merge() {
    var lang = (window.mvmOS && window.mvmOS.lang) || 'en';
    var table = tables[lang] || tables[lang.split('-')[0]] || en;
    window._i18n = window._i18n || {};
    Object.keys(table).forEach(function (k) { window._i18n[k] = table[k]; });
  }

  merge();
  if (window.mvmOS && window.mvmOS.onLangChange) window.mvmOS.onLangChange(merge);
  window.MSH_I18N = { en: en, bg: bg, de: de, es: es, fr: fr, ja: ja, 'pt-BR': ptBR, ru: ru, 'zh-CN': zhCN, tables: tables, merge: merge };
