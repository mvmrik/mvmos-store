// The bell reads notification text from window._i18n, where this app's own
// table never goes; only the cl_notif_* keys are merged in, for the language
// the desktop is on, so a verification notice reads right even before
// Classifieds is opened.
(function(){
  function merge(){
    var lang=(window.mvmOS&&window.mvmOS.lang)||"en";
    if(!window.CLASSIFIEDS_I18N[lang])lang=lang.indexOf("pt")===0?"pt-BR":lang.indexOf("zh")===0?"zh-CN":lang.split("-")[0];
    var table=window.CLASSIFIEDS_I18N[lang]||window.CLASSIFIEDS_I18N.en;
    window._i18n=window._i18n||{};
    Object.keys(table).forEach(function(k){if(k.indexOf("cl_notif_")===0)window._i18n[k]=table[k];});
  }
  merge();
  if(window.mvmOS&&window.mvmOS.onLangChange)window.mvmOS.onLangChange(merge);
})();
