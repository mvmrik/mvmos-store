  function apply(lang) {
    lang = lang || 'en';
    if (!STRINGS[lang]) lang = lang.indexOf('pt') === 0 ? 'pt-BR' : lang.indexOf('zh') === 0 ? 'zh-CN' : lang.split('-')[0];
    var table = STRINGS[lang] || STRINGS.en;
    window._i18n = window._i18n || {};
    for (var k in table) window._i18n[k] = table[k];
  }

